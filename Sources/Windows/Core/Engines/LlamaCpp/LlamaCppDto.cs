using System.Globalization;
using System.Text.Json.Serialization;

namespace Stratoscope.Core.Engines.LlamaCpp;

// The documents llama-server (tools/server of llama.cpp) sends, as typed records. Like Dto.cs: every property is nullable, null means the engine
// did not say, and a value of the wrong type is skipped. Names are the JSON keys. Booleans are read as text ("true" / "false") because the
// tolerant converters have no boolean reader. Only what Stratoscope shows is read.

/// <summary>One row of <c>GET /slots</c> (a top-level array, one row per slot): <c>server_slot::to_json</c>.</summary>
public sealed record LlamaSlotDto
{
    [JsonPropertyName("id")] public double? Id { get; init; }
    /// <summary>The slot's context size.</summary>
    [JsonPropertyName("n_ctx")] public double? ContextSize { get; init; }
    /// <summary>"true" while the slot runs a request (the slot state is anything but idle).</summary>
    [JsonPropertyName("is_processing")] public string? IsProcessing { get; init; }
    /// <summary>The id of the slot's current request, or of the last one while it is idle. Counts up; missing on a slot that never ran one.</summary>
    [JsonPropertyName("id_task")] public double? TaskId { get; init; }
    /// <summary>The tokens in the slot's memory: the prompt as far as it is read (cached tokens included), plus what has been generated. For an idle slot, the conversation it still holds.</summary>
    [JsonPropertyName("n_prompt_tokens")] public double? Tokens { get; init; }
    /// <summary>Prompt tokens of the running request that were read (not taken from the cache). Reset to 0 when the request ends.</summary>
    [JsonPropertyName("n_prompt_tokens_processed")] public double? Processed { get; init; }
    /// <summary>Prompt tokens of the running request that were reused from the slot's cache. Reset to 0 when the request ends.</summary>
    [JsonPropertyName("n_prompt_tokens_cache")] public double? Cached { get; init; }
    [JsonPropertyName("params"), JsonConverter(typeof(TolerantObject<LlamaSlotParamsDto>))] public LlamaSlotParamsDto? Params { get; init; }
    /// <summary>A one-element array: the generation state of the request.</summary>
    [JsonPropertyName("next_token"), JsonConverter(typeof(TolerantList<LlamaNextTokenDto>))] public List<LlamaNextTokenDto?>? NextToken { get; init; }

    [JsonIgnore] public bool Processing => string.Equals(IsProcessing, "true", StringComparison.OrdinalIgnoreCase);
    /// <summary>Tokens generated by the running request so far; null when the slot does not say.</summary>
    [JsonIgnore] public double? Generated => NextToken?.FirstOrDefault(n => n != null)?.Decoded;
    /// <summary>The request's token limit, or null for "no limit" (llama-server sends -1) and for a slot that does not say.</summary>
    [JsonIgnore] public double? TokenLimit => Params?.MaxTokens is > 0 ? Params.MaxTokens : Params?.Predict is > 0 ? Params.Predict : null;
}

public sealed record LlamaSlotParamsDto
{
    [JsonPropertyName("max_tokens")] public double? MaxTokens { get; init; }
    [JsonPropertyName("n_predict")] public double? Predict { get; init; }
}

public sealed record LlamaNextTokenDto
{
    /// <summary>Tokens generated by the request so far; 0 while the prompt is still being read.</summary>
    [JsonPropertyName("n_decoded")] public double? Decoded { get; init; }
}

/// <summary>The parts of <c>GET /props</c> that Stratoscope uses (<c>get_res_props</c>). It stays answerable while the server sleeps.</summary>
public sealed record LlamaProps
{
    [JsonPropertyName("total_slots")] public double? TotalSlots { get; init; }
    [JsonPropertyName("model_alias")] public string? ModelAlias { get; init; }
    /// <summary>The build, for example "b6789-1a2b3c4".</summary>
    [JsonPropertyName("build_info")] public string? BuildInfo { get; init; }
    [JsonPropertyName("default_generation_settings"), JsonConverter(typeof(TolerantObject<LlamaGenerationSettingsDto>))] public LlamaGenerationSettingsDto? Generation { get; init; }
    /// <summary>"true" when the server was started with <c>--metrics</c>.</summary>
    [JsonPropertyName("endpoint_metrics")] public string? EndpointMetrics { get; init; }
    /// <summary>"true" while the model is unloaded for idleness; asking <c>/slots</c> then would wake it.</summary>
    [JsonPropertyName("is_sleeping")] public string? IsSleeping { get; init; }

    [JsonIgnore] public bool Sleeping => string.Equals(IsSleeping, "true", StringComparison.OrdinalIgnoreCase);
    [JsonIgnore] public bool MetricsDisabled => string.Equals(EndpointMetrics, "false", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// True for a llama-server: its <c>/props</c> carries the slot count together with the default generation settings or the build. No other
    /// engine behind a router sends such a document, which is how <see cref="AutoEngineProvider"/> tells it from Strata.
    /// </summary>
    [JsonIgnore] public bool IsLlamaServer => TotalSlots.HasValue && (Generation != null || BuildInfo != null);
}

public sealed record LlamaGenerationSettingsDto
{
    [JsonPropertyName("n_ctx")] public double? ContextSize { get; init; }
}

/// <summary>
/// The numbers of <c>GET /metrics</c> (Prometheus text, needs <c>--metrics</c>), by their llama.cpp names without the <c>llamacpp:</c> prefix.
/// The two speeds are gauges averaged over the time since the previous scrape (the server resets them on every scrape) and are 0 when nothing
/// ran in that time, so a speed of 0 means "nothing measured", not "stalled".
/// </summary>
public sealed record LlamaCppMetrics
{
    public double? PromptTokensTotal { get; init; }
    public double? PromptTokensCachedTotal { get; init; }
    public double? PromptSecondsTotal { get; init; }
    public double? TokensPredictedTotal { get; init; }
    public double? TokensPredictedSecondsTotal { get; init; }
    public double? PromptTokensPerSecond { get; init; }
    public double? PredictedTokensPerSecond { get; init; }
    public double? RequestsProcessing { get; init; }
    public double? RequestsDeferred { get; init; }

    private const string Prefix = "llamacpp:";

    /// <summary>
    /// Reads the text format (<c>name value</c> lines, <c>#</c> comments). Series with labels are skipped, a value that is not a finite number is
    /// unknown. Null when the text has no <c>llamacpp:</c> metric at all.
    /// </summary>
    public static LlamaCppMetrics? Parse(string? text)
    {
        var values = PrometheusText.Parse(text, Prefix).Where(pair => !pair.Key.Contains('{')).ToDictionary(pair => pair.Key, pair => pair.Value);
        if (values.Count == 0) return null;
        double? V(string name) => values.TryGetValue(name, out var v) ? v : null;
        return new LlamaCppMetrics
        {
            PromptTokensTotal = V("prompt_tokens_total"), PromptTokensCachedTotal = V("prompt_tokens_cached_total"), PromptSecondsTotal = V("prompt_seconds_total"),
            TokensPredictedTotal = V("tokens_predicted_total"), TokensPredictedSecondsTotal = V("tokens_predicted_seconds_total"),
            PromptTokensPerSecond = V("prompt_tokens_seconds"), PredictedTokensPerSecond = V("predicted_tokens_seconds"),
            RequestsProcessing = V("requests_processing"), RequestsDeferred = V("requests_deferred"),
        };
    }
}
