import Foundation

// SPEED RULE (name the source of every value; never estimate).
// When several requests run together, the headline decode speed (and the headline prefill speed while reading) is the engine's
// own total over all requests. Each engine reports that total itself:
//  - Strata: live.tok_s, the total of the generating requests (serve/server.py _tok_s). The prefill headline is
//    live.prefill_tok_s_mean, the engine's mean. The Windows Strata adapter also has a fallback: when the engine has no total yet,
//    it sums derived per-slot speeds; the macOS reader does not have that fallback.
//  - Basalt: live.tok_s, which the engine sums over its slots.
//  - llama.cpp: /metrics llamacpp:predicted_tokens_seconds, the server-wide decode rate over all slots (prompt_tokens_seconds for
//    prefill). It needs the server's --metrics flag. No sum is used.
//  - custom: /ui/state tick.sample.decode_tps and tick.sample.prefill_tps, the engine's counter deltas over all requests between
//    samples. The per-request sum is used only when the sample has no rate.
// A request's own speed is shown on its own row only. Never add up the per-request rows to make the headline unless the engine
// has no total.
// This file: the llama.cpp source is /metrics llamacpp:predicted_tokens_seconds (decode) and llamacpp:prompt_tokens_seconds (prefill).

// The documents llama-server (tools/server of llama.cpp) sends, read from untyped JSON. Port of LlamaCppDto.cs: every value is optional,
// nil means the engine did not say, and a value of the wrong type is skipped (never turned into 0).

private func number(_ o: [String: Any], _ key: String) -> Double? { (o[key] as? NSNumber)?.doubleValue }

/// A JSON boolean, or the text "true" / "false"; anything else is unknown.
private func flag(_ o: [String: Any], _ key: String) -> Bool? {
    if let b = o[key] as? Bool { return b }
    if let s = o[key] as? String {
        switch s.lowercased() {
        case "true": return true
        case "false": return false
        default: return nil
        }
    }
    return nil
}

/// One row of `GET /slots` (a top-level array, one row per slot): `server_slot::to_json`.
struct LlamaSlot {
    var id: Double?
    /// The slot's context size.
    var contextSize: Double?
    /// nil when the row does not carry the flag; true while the slot runs a request.
    var isProcessing: Bool?
    /// The id of the slot's current request, or of the last one while it is idle. Counts up; missing on a slot that never ran one.
    var taskId: Double?
    /// The tokens in the slot's memory: the prompt as far as it is read (cached tokens included), plus what has been generated.
    var tokens: Double?
    /// Prompt tokens of the running request that were read (not taken from the cache). Reset to 0 when the request ends.
    var processed: Double?
    /// Prompt tokens of the running request that were reused from the slot's cache. Reset to 0 when the request ends.
    var cached: Double?
    /// Tokens generated by the running request so far (`next_token[0].n_decoded`); nil when the slot does not say.
    var generated: Double?
    /// The request's token limit, or nil for "no limit" (llama-server sends -1) and for a slot that does not say.
    var tokenLimit: Double?

    init(_ o: [String: Any]) {
        id = number(o, "id"); contextSize = number(o, "n_ctx"); isProcessing = flag(o, "is_processing"); taskId = number(o, "id_task")
        tokens = number(o, "n_prompt_tokens"); processed = number(o, "n_prompt_tokens_processed"); cached = number(o, "n_prompt_tokens_cache")
        // `next_token` is a one-element array; the first object in it is the request's generation state.
        generated = (o["next_token"] as? [Any])?.lazy.compactMap { $0 as? [String: Any] }.first.flatMap { number($0, "n_decoded") }
        let params = o["params"] as? [String: Any]
        if let m = params.flatMap({ number($0, "max_tokens") }), m > 0 { tokenLimit = m }
        else if let p = params.flatMap({ number($0, "n_predict") }), p > 0 { tokenLimit = p }
        else { tokenLimit = nil }
    }

    var processing: Bool { isProcessing == true }
}

/// The parts of `GET /props` that Stratoscope uses (`get_res_props`). It stays answerable while the server sleeps.
struct LlamaProps {
    var totalSlots: Double?
    var modelAlias: String?
    /// The build, for example "b6789-1a2b3c4".
    var buildInfo: String?
    /// `default_generation_settings.n_ctx`.
    var contextSize: Double?
    var hasGenerationSettings: Bool
    /// `endpoint_metrics`: true when the server was started with `--metrics`.
    var endpointMetrics: Bool?
    /// `is_sleeping`: the model is unloaded for idleness; asking `/slots` then would wake it.
    var sleeping: Bool

    init(_ o: [String: Any]) {
        totalSlots = number(o, "total_slots"); modelAlias = o["model_alias"] as? String; buildInfo = o["build_info"] as? String
        let generation = o["default_generation_settings"] as? [String: Any]
        hasGenerationSettings = generation != nil
        contextSize = generation.flatMap { number($0, "n_ctx") }
        endpointMetrics = flag(o, "endpoint_metrics"); sleeping = flag(o, "is_sleeping") == true
    }

    var metricsDisabled: Bool { endpointMetrics == false }

    /// True for a llama-server: its `/props` carries the slot count together with the default generation settings or the build. No other
    /// engine behind a router sends such a document.
    var isLlamaServer: Bool { totalSlots != nil && (hasGenerationSettings || buildInfo != nil) }
}

/// The numbers of `GET /metrics` (Prometheus text, needs `--metrics`), by their llama.cpp names without the `llamacpp:` prefix.
/// The two speeds are gauges averaged over the time since the previous scrape (the server resets them on every scrape) and are 0 when
/// nothing ran in that time, so a speed of 0 means "nothing measured", not "stalled".
struct LlamaCppMetrics {
    static let prefix = "llamacpp:"

    var promptTokensTotal: Double?
    var promptTokensCachedTotal: Double?
    var promptSecondsTotal: Double?
    var tokensPredictedTotal: Double?
    var tokensPredictedSecondsTotal: Double?
    var promptTokensPerSecond: Double?
    var predictedTokensPerSecond: Double?
    var requestsProcessing: Double?
    var requestsDeferred: Double?

    /// Series with labels are skipped, a value that is not a finite number is unknown. nil when the text has no `llamacpp:` metric at all.
    static func parse(_ text: String?) -> LlamaCppMetrics? {
        let v = PrometheusText.parse(text, prefix: prefix).filter { !$0.key.contains("{") }
        if v.isEmpty { return nil }
        return LlamaCppMetrics(
            promptTokensTotal: v["prompt_tokens_total"], promptTokensCachedTotal: v["prompt_tokens_cached_total"],
            promptSecondsTotal: v["prompt_seconds_total"], tokensPredictedTotal: v["tokens_predicted_total"],
            tokensPredictedSecondsTotal: v["tokens_predicted_seconds_total"], promptTokensPerSecond: v["prompt_tokens_seconds"],
            predictedTokensPerSecond: v["predicted_tokens_seconds"], requestsProcessing: v["requests_processing"],
            requestsDeferred: v["requests_deferred"])
    }
}

/// Reads llama-server, the HTTP server of llama.cpp, behind a llama-swap router or directly. Port of LlamaCppProvider.cs.
///
/// Data sources, all GET:
///  - `/props`: identity (the llama-server check), the build, the slot count, the context size, whether the server sleeps and whether
///    `--metrics` is on. The server answers it while asleep; `/slots` would wake it, so a sleeping server is shown as "Asleep" and
///    `/slots` is not asked.
///  - `/slots`: per slot whether it runs a request, the tokens in its memory, how many prompt tokens were read and how many reused from
///    the cache, how many tokens were generated. There is no phase field: a running slot with 0 generated tokens is reading its prompt.
///  - `/metrics` (Prometheus text, only with `--metrics`): the prompt and generation speeds, the waiting requests and the totals. The
///    server resets the speed gauges on every scrape, so they are the average since the previous poll (and 0 when nothing ran: unknown).
///
/// What llama-server does not say is not drawn: the size of the whole prompt (so no percentage while it is read), when a request ends and
/// what it came to, RAM, video card and CPU. A missing or refused `/slots` is nil (no snapshot), never 0; a 429 from the router keeps the
/// previous read of the same engine, marked `routerLimited`.
public final class LlamaCppReader {
    /// The value of `engine:` in the config file.
    public static let id = "llamacpp"
    public static let brand = "llama.cpp"

    /// `.notLlama`: `/props` is no llama-server's (the caller goes on with the other engines). `.read(nil)`: it is one, but gave no snapshot.
    enum Outcome {
        case notLlama
        case read(EngineSnapshot?)
    }

    private let http = JSONFetcher()
    private var previous: (base: String, snapshot: EngineSnapshot)?

    public init() {}

    /// Asks `<base>/props` first. Not a llama-server: `.notLlama`. A sleeping one: the "Asleep" placeholder. Otherwise `<base>/slots` and, unless
    /// `--metrics` is off, `<base>/metrics`. `model` is the router's name for the model; nil without a router (the server's own alias is used).
    func read(base: String, model: String?, compactAt: Double?, links: [EngineLink], _ completion: @escaping (Outcome) -> Void) {
        http.get(base + "/props") { [self] object in
            guard let object = object else { completion(.notLlama); return }
            let props = LlamaProps(object)
            guard props.isLlamaServer else { completion(.notLlama); return }
            let name = model ?? props.modelAlias ?? Self.brand
            if props.sleeping {
                previous = nil
                completion(.read(EngineSnapshot(engine: Self.brand, model: name, status: .loading("Asleep"), context: ContextUsage(max: 0), links: links)))
                return
            }
            http.getText(base + "/slots") { [self] code, body in
                if code == 429 {
                    // The router limits the rate: the previous read of this engine, marked, or nothing.
                    if let p = previous, p.base == base { var s = p.snapshot; s.routerLimited = true; completion(.read(s)) }
                    else { completion(.read(nil)) }
                    return
                }
                guard let code = code, (200..<300).contains(code), let body = body, let rows = Self.slots(from: body) else {
                    completion(.read(nil)); return      // no /slots: unknown, not an empty server
                }
                // Without a router the document must look like a slot list; a router already vouched for the engine.
                if model == nil && !rows.contains(where: { $0.contextSize != nil || $0.isProcessing != nil }) {
                    completion(.read(nil)); return
                }
                let finish: (LlamaCppMetrics?) -> Void = { [self] metrics in
                    let s = translate(rows, props: props, metrics: metrics, model: name, compactAt: compactAt, links: links)
                    previous = (base, s)
                    completion(.read(s))
                }
                if props.metricsDisabled { finish(nil); return }
                http.getText(base + "/metrics") { code, text in
                    // Refused metrics (for example 501) leave the speeds and totals unknown and the rest shown.
                    finish(code.map { (200..<300).contains($0) } == true ? LlamaCppMetrics.parse(text) : nil)
                }
            }
        }
    }

    /// The rows of a `/slots` answer: a top-level JSON array; entries that are no object are dropped. nil when the text is no array.
    static func slots(from text: String) -> [LlamaSlot]? {
        guard let array = (try? JSONSerialization.jsonObject(with: Data(text.utf8))) as? [Any] else { return nil }
        return array.compactMap { ($0 as? [String: Any]).map(LlamaSlot.init) }
    }

    /// Translates the `/slots` rows (with `/props` and `/metrics`, when they were asked for) into a snapshot. Internal so tests can feed
    /// recorded payloads.
    func translate(_ rows: [LlamaSlot], props: LlamaProps?, metrics: LlamaCppMetrics?, model: String, compactAt: Double? = nil,
                   links: [EngineLink] = []) -> EngineSnapshot {
        let running = rows.filter { $0.processing }
        // A running slot that has generated nothing yet reads its prompt (the rule Strata uses when an engine gives no phase); one that
        // does not say how much it generated counts as reading.
        let writers = running.filter { ($0.generated ?? 0) > 0 }
        let readers = running.filter { !(($0.generated ?? 0) > 0) }
        let status: EngineStatus = running.isEmpty ? .idle : !writers.isEmpty ? .decode : .prefill

        // /slots resets the counters of a request when it ends, so a slot that has just started shows 0 read and 0 reused until its first
        // batch: that is "not known yet", and tokens are only taken from a slot whose request has begun to count.
        func counting(_ s: LlamaSlot) -> Bool { (s.generated ?? 0) > 0 || (s.processed ?? 0) > 0 || (s.cached ?? 0) > 0 }

        let together = running.count > 1
        let row = running.first
        var live: LiveRequest?
        if status != .idle {
            let reading = status == .prefill
            var read: Double?
            let generated: Double?
            if reading {
                // The engine does not say how long the prompt is, so there is no total and no percentage.
                read = readers.allSatisfy(counting) && readers.allSatisfy({ $0.tokens != nil }) ? readers.reduce(0) { $0 + $1.tokens! } : nil
                generated = readers.allSatisfy({ $0.generated == 0 }) ? 0 : nil      // "0" is the engine's word; a slot that says nothing is unknown
            } else {
                generated = writers.allSatisfy({ $0.generated != nil }) ? writers.reduce(0) { $0 + $1.generated! } : nil
            }
            let reused: Double? = (!together && row != nil && counting(row!)) ? row!.cached : nil
            let promptSpeed = metrics?.promptTokensPerSecond, decodeSpeed = metrics?.predictedTokensPerSecond
            live = LiveRequest(
                promptRead: read, promptTotal: nil, generated: generated,
                maxTokens: together ? nil : row?.tokenLimit,
                prefillTokensPerSecond: reading && (promptSpeed ?? 0) > 0 ? promptSpeed : nil,
                decodeTokensPerSecond: !writers.isEmpty && (decodeSpeed ?? 0) > 0 ? decodeSpeed : nil,
                reusedEstimate: reused,          // the engine's own count (the field also carries Strata's estimates)
                running: together ? running.count : nil)
        }

        // One entry per slot, for a server with more than one.
        var batchSlots: [BatchSlot]?
        if rows.count > 1 {
            batchSlots = rows.enumerated().map { position, s in
                BatchSlot(
                    index: Int(s.id ?? Double(position)),
                    state: !s.processing ? "idle" : (s.generated ?? 0) > 0 ? "decoding" : "reading",
                    heldTokens: s.tokens,        // the slot's memory: the conversation it holds, a running request's prompt and what it wrote
                    promptRead: s.processing && !((s.generated ?? 0) > 0) && counting(s) ? s.tokens : nil,
                    generated: s.processing ? s.generated : nil,
                    maxTokens: s.processing ? s.tokenLimit : nil)
            }
        }

        // The fullest running slot, or while idle the slot that ran last (the conversation the next request continues).
        var used: Double?
        if running.isEmpty {
            var newest: LlamaSlot?
            for s in rows { if let t = s.taskId, t > (newest?.taskId ?? -Double.infinity) { newest = s } }
            used = newest?.tokens
        } else {
            used = running.filter { ($0.generated ?? 0) > 0 || counting($0) }.compactMap { $0.tokens }.max()
        }
        // 0 = the engine did not say (the Mac model's maximum is not optional).
        let max = rows.compactMap { $0.contextSize }.max() ?? props?.contextSize ?? 0

        // Counters since the server started. "Prompt tokens" counts what was read and what was reused; the engine has no request count.
        var info = EngineInfo(version: props?.buildInfo, batchSlots: props?.totalSlots)
        var hasInfo = props != nil && (props?.buildInfo != nil || props?.totalSlots != nil)
        if let m = metrics, m.promptTokensTotal != nil || m.tokensPredictedTotal != nil {
            hasInfo = true
            if let read = m.promptTokensTotal, let cached = m.promptTokensCachedTotal { info.totalPromptTokens = read + cached }
            info.totalReusedTokens = m.promptTokensCachedTotal
            info.totalOutputTokens = m.tokensPredictedTotal
            info.totalPromptMilliseconds = m.promptSecondsTotal.map { $0 * 1000 }
            info.totalDecodeMilliseconds = m.tokensPredictedSecondsTotal.map { $0 * 1000 }
        }

        return EngineSnapshot(engine: Self.brand, model: model, status: status,
                              queued: Int(Swift.max(0, Swift.min(metrics?.requestsDeferred ?? 0, 1e9))),
                              live: live, recent: [], context: ContextUsage(used: used, max: max, compactAt: compactAt),
                              links: links, engineVersion: props?.buildInfo, info: hasInfo ? info : nil, slots: batchSlots)
    }
}
